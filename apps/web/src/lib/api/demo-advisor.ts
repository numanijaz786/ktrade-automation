/**
 * Demo advisor, used by `DemoApiClient`. Demo prices are SIMULATED, so the advisor gives exactly the answer the
 * real engine gives on simulated prices: "Not enough verified data to recommend anything", with no entry,
 * stop, target or confidence anywhere. Nothing here fabricates a recommendation that could look real.
 * Holdings show only the P&L facts the demo ledger already has, labelled SIMULATED.
 */
import type { ApiClient } from './client';
import { ApiError } from './errors';
import { validateRiskPct } from './advisor-rules';
import type { AdvisorSettings, DailyReport, HoldingAdvice, NotEnoughData } from './types-advisor';
import type { DashboardSummary, Holding, Portfolio } from './types';

export interface DemoAdvisorDeps {
  latencyMs: number;
  now: () => number;
  portfolios: () => Promise<Portfolio[]>;
  holdings: (pf: string) => Promise<Holding[]>;
  summary: (pf: string) => Promise<DashboardSummary>;
}

export const DEMO_NOT_ENOUGH_HEADLINE = 'Not enough verified data to recommend anything';
const SIM_REASON = 'simulated data — not for investment decisions';
const DISCLAIMER =
  'Research aid generated by deterministic rules from stored data. Not financial advice; no return is guaranteed. Execution is always a separate, human-approved step.';

export function createDemoAdvisor(deps: DemoAdvisorDeps): ApiClient['advisor'] {
  const wait = async () => {
    if (deps.latencyMs > 0) await new Promise((r) => setTimeout(r, deps.latencyMs));
  };
  const iso = () => new Date(deps.now()).toISOString();
  let settings: AdvisorSettings = { riskPerTradePct: '1', isDefault: true };

  const holdingAdvice = async (pf: string): Promise<HoldingAdvice[]> => {
    const list = await deps.holdings(pf);
    return list.map((h): HoldingAdvice => {
      const last = h.lastPrice;
      return {
        symbol: h.symbol,
        name: h.name,
        sector: h.sector,
        quantity: h.quantity,
        avgCost: h.avgCost,
        price: last
          ? { value: last.value, source: 'SIMULATED', asOfBar: '', barTs: last.asOf ?? '', verified: false }
          : null,
        marketValue: h.marketValue,
        pnl:
          last && h.marketValue && h.unrealizedPnl
            ? {
                lastPrice: last.value,
                costBasis: h.totalCost,
                marketValue: h.marketValue,
                unrealizedGross: h.unrealizedPnl,
                // The demo ledger has no fee-aware figure: unavailable, not guessed.
                estimatedSellFees: null,
                unrealizedNet: null,
                unrealizedNetPct: null,
                realizedPnl: h.realizedPnl,
                dividendsReceived: null,
                totalReturn: null,
                totalReturnPct: null,
                priceSource: 'SIMULATED',
              }
            : null,
        status: 'NOT_ACTIONABLE',
        advice: null,
        headline: `No holding advice: ${SIM_REASON}`,
        notActionableReasons: [SIM_REASON],
        reasons: [],
        suggestedSellQty: null,
        stop: null,
        targets: [],
        targetsReached: 0,
        sellRange: null,
        planNote: 'No stored BUY plan for this stock and horizon, so no targets are shown.',
        invalidations: [],
        dividendsConsidered: null,
        warnings: [],
        explanation: null,
      };
    });
  };

  const notEnough = (n: number): NotEnoughData => ({
    summary: `None of the ${n} stocks could be evaluated on verified data: ${n} are SIMULATED, 0 are stale. No target, entry or stop is given for any of them.`,
    evaluated: n,
    simulated: n,
    stale: 0,
    reasons: [{ reason: SIM_REASON, count: n, symbols: [] }],
  });

  return {
    dailyReport: async ({ portfolioId, horizon }) => {
      await wait();
      const [pfs, sum, adv] = await Promise.all([
        deps.portfolios(),
        deps.summary(portfolioId),
        holdingAdvice(portfolioId),
      ]);
      const pf = pfs.find((p) => p.id === portfolioId);
      const n = adv.length;
      const r: DailyReport = {
        generatedAt: iso(),
        dataAsOf: null,
        horizon,
        portfolio: {
          id: portfolioId,
          name: pf?.name ?? '',
          cash: sum.cash.ledger.value,
          equity: sum.accountValue.value,
        },
        dataQuality: {
          sources: { SIMULATED: n },
          freshest: null,
          staleCount: 0,
          simulatedShare: n > 0 ? '100.00' : null,
          missingFundamentalsCount: n,
          coverageNote:
            'Demo mode: every price is SIMULATED, so nothing can be evaluated on verified data. Connect a real market-data source (API mode) to get recommendations. News is owner-entered only.',
        },
        headline: DEMO_NOT_ENOUGH_HEADLINE,
        notEnoughData: notEnough(n),
        topBuys: [],
        avoidOrSell: [],
        holds: [],
        opportunities: [],
        holdingsAdvice: adv,
        whatChanged: {
          baseline: false,
          compared: 0,
          events: [],
          note: 'No earlier stored recommendation for this horizon to compare with.',
        },
        newsImpact: {
          windowHours: 72,
          coverage: 'sources: owner-entered only',
          lastUpdated: null,
          items: [],
          note: 'No announcements for held or watched symbols in the last 72 hours.',
        },
        portfolioNotes: [
          {
            kind: 'SIMULATED_PRICES',
            severity: 'WARN',
            text: 'Some holdings are valued on SIMULATED prices: the profit and loss shown is for testing only.',
          },
        ],
        disclaimer: DISCLAIMER,
      };
      return r;
    },
    holdings: async ({ portfolioId, horizon }) => {
      await wait();
      return { portfolioId, horizon, generatedAt: iso(), holdings: await holdingAdvice(portfolioId) };
    },
    scanner: async ({ filter, horizon }) => {
      await wait();
      return {
        horizon,
        filter,
        generatedAt: iso(),
        universe: 0,
        verifiedEvaluations: 0,
        results: [],
        note: 'No stock has verified, fresh data to scan.',
      };
    },
    stock: async (symbol) => {
      await wait();
      const sym = symbol.trim().toUpperCase();
      const rows = await deps.portfolios();
      const first = rows[0];
      const held = first ? (await deps.holdings(first.id)).find((h) => h.symbol === sym) : undefined;
      return {
        symbol: sym,
        name: held?.name ?? sym,
        sector: held?.sector ?? null,
        generatedAt: iso(),
        price: held?.lastPrice
          ? {
              value: held.lastPrice.value,
              source: 'SIMULATED',
              asOfBar: '',
              barTs: held.lastPrice.asOf ?? '',
              verified: false,
            }
          : null,
        technicals: null,
        ratios: null,
        ratiosReason: 'no financial statements are stored for this symbol (or no price)',
        valuation: {
          status: 'UNAVAILABLE',
          facts: [],
          assumptions: [],
          fairValueLow: null,
          fairValueHigh: null,
          marginOfSafetyPct: null,
          explanation: [],
          reason:
            'needs financial statements and at least 3 same-sector peers (or supplied valuation assumptions)',
        },
        announcements: [],
        recommendations: {},
        dataSources: {
          bars: { count: 0, latestBarTs: null, latestBarSource: 'SIMULATED', sources: ['SIMULATED'] },
          quote: null,
          fundamentals: null,
          stale: false,
        },
      };
    },
    run: async ({ portfolioId }) => {
      await wait();
      const adv = await holdingAdvice(portfolioId);
      return {
        portfolioId,
        runAt: iso(),
        universe: adv.length,
        skippedNoBars: 0,
        evaluated: 0,
        stored: 0,
        alreadyStored: 0,
        actionable: 0,
        notActionable: 0,
        failed: 0,
      };
    },
    settings: async () => {
      await wait();
      return { ...settings };
    },
    updateSettings: async (riskPerTradePct) => {
      await wait();
      const err = validateRiskPct(riskPerTradePct);
      if (err)
        throw new ApiError('VALIDATION_FAILED', 422, 'Validation failed', undefined, {
          errors: [{ path: 'riskPerTradePct', message: err }],
        });
      settings = { riskPerTradePct: riskPerTradePct.trim(), isDefault: false };
      return { ...settings };
    },
  };
}
