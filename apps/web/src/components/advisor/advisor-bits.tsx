'use client';

import type { ReactNode } from 'react';
import Link from 'next/link';
import { AlertTriangle, DatabaseZap, ShieldAlert } from 'lucide-react';
import { PROVENANCE } from '@/components/provenance-badge';
import { StatusPill, type StatusTone } from '@/components/status-badge';
import { Alert, AlertDescription, AlertTitle } from '@/components/ui/alert';
import { ACTION_LABEL, priceLabel } from '@/lib/api/advisor-rules';
import type { AdvisorAction, AdvisorDataQuality, AdvisorPrice, NotEnoughData } from '@/lib/api/types-advisor';
import { formatDateTime, formatNumber, formatPercent } from '@/lib/format';

/** A value the API did not return. Never replaced by a guess. */
export function Unavailable({ what }: { what?: string }) {
  return (
    <span className="text-muted-foreground" data-testid="unavailable">
      {what ? `${what} unavailable` : 'unavailable'}
    </span>
  );
}

const ACTION_TONE: Record<AdvisorAction, StatusTone> = {
  STRONG_BUY: 'good',
  BUY: 'good',
  HOLD: 'neutral',
  WATCHLIST: 'info',
  SELL: 'bad',
  AVOID: 'bad',
};

export function ActionBadge({ action }: { action: AdvisorAction | null }) {
  if (!action) return <StatusPill tone="neutral">No recommendation</StatusPill>;
  return <StatusPill tone={ACTION_TONE[action]}>{ACTION_LABEL[action]}</StatusPill>;
}

/**
 * The latest price WITH where it came from, when it is from, and a plain label:
 * Simulated, Estimated, Imported, Delayed, stale. A price is never shown without these.
 */
export function PriceLine({ price, className }: { price: AdvisorPrice | null; className?: string }) {
  if (!price) return <Unavailable what="Latest price" />;
  const label = priceLabel(price);
  return (
    <span className={`inline-flex flex-wrap items-center gap-x-2 gap-y-1 ${className ?? ''}`}>
      <span className="font-medium tabular">Rs {formatNumber(price.value, { dp: 2 })}</span>
      <StatusPill tone={label.tone}>
        <span data-testid="price-label">{label.text}</span>
      </StatusPill>
      <span className="text-xs text-muted-foreground">
        Source: {PROVENANCE[price.source].label}
        {price.barTs
          ? ` · as of ${formatDateTime(price.barTs)}`
          : price.asOfBar
            ? ` · as of ${price.asOfBar}`
            : ''}
      </span>
    </span>
  );
}

export function Disclaimer({ text }: { text?: string }) {
  return (
    <p className="rounded-lg border bg-muted/40 p-3 text-xs text-muted-foreground" data-testid="disclaimer">
      {text ||
        'Research aid generated by deterministic rules from stored data. Not financial advice; no return is guaranteed.'}{' '}
      Nothing here places an order: you always decide and place trades yourself.
    </p>
  );
}

/** Always visible: where the data comes from and how fresh it is. */
export function DataQualityBanner({ q }: { q: AdvisorDataQuality }) {
  const sources = Object.entries(q.sources);
  const bad = q.staleCount > 0 || (q.simulatedShare !== null && q.simulatedShare !== '0.00');
  return (
    <section
      aria-label="Data quality"
      data-testid="data-quality"
      className={`rounded-lg border p-4 text-sm ${bad ? 'border-amber-600/40 bg-amber-500/5' : 'bg-muted/30'}`}
    >
      <h2 className="mb-2 flex items-center gap-2 font-semibold">
        <DatabaseZap className="size-4" aria-hidden="true" /> Data quality
      </h2>
      <dl className="grid gap-x-6 gap-y-2 sm:grid-cols-2 lg:grid-cols-4">
        <div>
          <dt className="text-xs text-muted-foreground">Price sources (stocks)</dt>
          <dd>
            {sources.length === 0
              ? 'none'
              : sources
                  .map(
                    ([s, n]) => `${(PROVENANCE as Record<string, { label: string }>)[s]?.label ?? s}: ${n}`,
                  )
                  .join(', ')}
          </dd>
        </div>
        <div>
          <dt className="text-xs text-muted-foreground">Freshest data</dt>
          <dd>{q.freshest ? formatDateTime(q.freshest) : 'none'}</dd>
        </div>
        <div>
          <dt className="text-xs text-muted-foreground">Stale / simulated</dt>
          <dd>
            {q.staleCount} stale ·{' '}
            {q.simulatedShare === null
              ? 'simulated share unavailable'
              : `${formatPercent(q.simulatedShare)} simulated`}
          </dd>
        </div>
        <div>
          <dt className="text-xs text-muted-foreground">Missing company financials</dt>
          <dd>{q.missingFundamentalsCount} stocks</dd>
        </div>
      </dl>
      {q.coverageNote && <p className="mt-2 text-muted-foreground">{q.coverageNote}</p>}
      <p className="mt-2">
        <Link href="/data-health" className="font-medium underline underline-offset-2">
          See data providers and how to fix this
        </Link>
      </p>
    </section>
  );
}

/** Shown INSTEAD of any recommendation when the API says it cannot give one. No levels are rendered. */
export function NotEnoughDataPanel({ n }: { n: NotEnoughData }) {
  const sorted = [...n.reasons].sort((a, b) => {
    const sim = (r: string) => (r.toLowerCase().includes('simulated') ? 0 : 1);
    return sim(a.reason) - sim(b.reason) || b.count - a.count;
  });
  return (
    <Alert data-testid="not-enough-data">
      <ShieldAlert aria-hidden="true" />
      <AlertTitle>Why there is no recommendation</AlertTitle>
      <AlertDescription className="space-y-3">
        <p>{n.summary}</p>
        {sorted.length > 0 && (
          <ul className="list-disc space-y-1 pl-5">
            {sorted.map((r) => (
              <li key={r.reason}>
                {r.reason.toLowerCase().includes('simulated') ? <strong>{r.reason}</strong> : r.reason}{' '}
                <span className="text-muted-foreground">
                  ({r.count} stock{r.count === 1 ? '' : 's'}
                  {r.symbols.length ? `, e.g. ${r.symbols.join(', ')}` : ''})
                </span>
              </li>
            ))}
          </ul>
        )}
        <div>
          <p className="font-medium">What you can do</p>
          <ul className="list-disc pl-5">
            <li>
              Open{' '}
              <Link className="underline underline-offset-2" href="/data-health">
                Data providers
              </Link>{' '}
              and connect or refresh a real market-data source.
            </li>
            <li>
              Enter company financials on the{' '}
              <Link className="underline underline-offset-2" href="/financials">
                Financial statements
              </Link>{' '}
              page.
            </li>
            <li>Come back after the market closes: the advisor uses completed daily prices.</li>
          </ul>
        </div>
      </AlertDescription>
    </Alert>
  );
}

export function WarningList({ items, title }: { items: string[]; title?: string }) {
  if (items.length === 0) return null;
  return (
    <div className="space-y-1 rounded-md border border-amber-600/40 bg-amber-500/5 p-2 text-sm">
      <p className="flex items-center gap-1.5 font-medium">
        <AlertTriangle className="size-4" aria-hidden="true" /> {title ?? 'Warnings'}
      </p>
      <ul className="list-disc pl-6">
        {items.map((w) => (
          <li key={w}>{w}</li>
        ))}
      </ul>
    </div>
  );
}

export function KeyValue({ label, children }: { label: string; children: ReactNode }) {
  return (
    <div>
      <dt className="text-xs text-muted-foreground">{label}</dt>
      <dd className="text-sm font-medium tabular">{children}</dd>
    </div>
  );
}
