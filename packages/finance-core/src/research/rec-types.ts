export interface RecommendationConfig {
  /** Minimum daily bars for SHORT_TERM and SWING. */
  readonly minBarsShort: number;
  /** Minimum daily bars for LONG_TERM, DIVIDEND, VALUE, GROWTH. */
  readonly minBarsLong: number;
  /** Average daily traded value (currency) below which the action is capped at WATCHLIST/AVOID. */
  readonly liquidityFloorTradedValue: Decimal;
  readonly atrPeriod: number;
  /** Minimum risk:reward to Target 2 for a BUY. */
  readonly minRiskReward: Decimal;
  readonly strongRiskReward: Decimal;
  /** Rule-weight coverage (%) below which the evaluation is NOT_ACTIONABLE ("insufficient evidence"). */
  readonly minCoveragePct: Decimal;
  readonly strongBuyBullMin: Decimal;
  readonly strongBuyBearMax: Decimal;
  readonly buyBullMin: Decimal;
  readonly buyBearMax: Decimal;
  readonly sellBearMin: Decimal;
  readonly sellBullMax: Decimal;
  readonly avoidBearMin: Decimal;
  readonly avoidSoftBearMin: Decimal;
  readonly avoidSoftBullMax: Decimal;
  readonly watchBullMin: Decimal;
  readonly buyConfidenceMin: Decimal;
  readonly strongBuyConfidenceMin: Decimal;
  /** Entry ceiling = price x (1 + this %). Default 0: never plan an entry above the last close. */
  readonly entryTolerancePct: Decimal;
  /** BUY is downgraded to WATCHLIST when close is more than this many ATRs above SMA20 ("extended"). */
  readonly extensionAtr: Decimal;
  readonly stopAtrMult: Readonly<Record<Horizon, Decimal>>;
  readonly targetAtrMults: Readonly<Record<Horizon, readonly [Decimal, Decimal, Decimal]>>;
  readonly maxFundamentalAgeDays: number;
  readonly annualiseQuarterly: boolean;
  // rule thresholds
  readonly rsiHealthyLow: Decimal;
  readonly rsiHealthyHigh: Decimal;
  readonly rsiOverbought: Decimal;
  readonly adxTrend: Decimal;
  readonly relVolMin: Decimal;
  readonly momentumStrong: Decimal;
  readonly momentumWeak: Decimal;
  readonly nearSupportAtr: Decimal;
  readonly roeMinPct: Decimal;
  readonly debtToEquityMax: Decimal;
  readonly debtToEquityBear: Decimal;
  readonly growthHighPct: Decimal;
  readonly dividendYieldMinPct: Decimal;
  readonly payoutMaxPct: Decimal;
  readonly peMaxValue: Decimal;
  readonly pbMaxValue: Decimal;
  readonly mosMinPct: Decimal;
  readonly mosValuePct: Decimal;
  readonly overvaluedPct: Decimal;
}

