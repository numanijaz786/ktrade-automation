export interface PortfolioContext {
  /** Total portfolio value (cash + holdings), same currency as prices. */
  readonly equity: Decimal;
  readonly cash: Decimal;
  /** Shares of this symbol currently held (0 if none). */
  readonly holdingQty: Decimal;
  /** Existing exposure to this stock's sector, % of equity (null = unknown, sector cap not applied). */
  readonly sectorExposurePct?: Decimal | null;
}

export interface RiskConfig {
  /** % of equity risked per trade (1 = 1%). */
  readonly riskPerTradePct: Decimal;
  /** Max % of equity in one stock. */
  readonly maxPositionPct: Decimal;
  /** Max % of equity in one sector (optional). */
  readonly maxSectorPct?: Decimal | null;
  readonly feeSchedule: FeeScheduleSpec | readonly FeeScheduleItemSpec[];
}

export interface MarketDataQuality {
  /** When the latest price was observed (ISO). */
  readonly priceAsOf: string;
  /** Price older than this many minutes at `asOf` is stale => NOT_ACTIONABLE. */
  readonly freshnessLimitMinutes: number;
  /** Known feed delay in minutes (informational; lowers the data-quality score when > 15). */
  readonly delayMinutes?: number | null;
}

export interface ValuationAssumptionsInput {
  /** Justified P/E from a supplied historical multiple (used when no peer median is available). */
  readonly historicalPe?: { readonly value: Decimal; readonly basis: string } | null;
  readonly ddm?: {
    readonly lastAnnualDps: ReportedFact;
    readonly growthPct: Decimal;
    readonly requiredReturnPct: Decimal;
    readonly basis: string;
  } | null;
  readonly dcf?: {
    readonly baseFcf: ReportedFact;
    readonly growthPct: Decimal;
    readonly years: number;
    readonly terminalGrowthPct: Decimal;
    readonly discountRatePct: Decimal;
    readonly netDebt: ReportedFact;
    readonly sharesOutstanding: ReportedFact;
    readonly basis: string;
  } | null;
}

export interface FundamentalsBundle {
  readonly current: FinancialStatement;
  readonly priorYear?: FinancialStatement | null;
  readonly priorQuarter?: FinancialStatement | null;
  /** Supplied peer multiples (>= 3 needed to be used). */
  readonly peers?: readonly PeerInput[] | null;
  readonly valuation?: ValuationAssumptionsInput | null;
}

export interface EvaluateStockInput {
  readonly symbol: string;
  readonly sector?: string | null;
  readonly horizon: Horizon;
  /** Decision time (ISO). Bars after this are ignored (look-ahead guard). */
  readonly asOf: string;
  /** Daily bars ascending by `ts`, up to and including the decision bar. */
  readonly bars: readonly ResearchBar[];
  readonly marketData: MarketDataQuality;
  /** Currency of prices (e.g. "PKR"). */
  readonly currency: string;
  readonly fundamentals?: FundamentalsBundle | null;
  readonly dividendHistory?: readonly DividendRecord[] | null;
  readonly portfolio: PortfolioContext;
  readonly risk: RiskConfig;
  readonly config?: Partial<RecommendationConfig>;
}

export type RuleDomain = 'TECHNICAL' | 'FUNDAMENTAL' | 'VALUATION';
export interface RuleOutcome {
  readonly id: string;
  readonly domain: RuleDomain;
  readonly side: 'BULL' | 'BEAR';
  readonly weight: number;
  /** Trend / fundamental deterioration: the only rules that can justify a SELL. */
  readonly structural: boolean;
  readonly label: string;
  readonly threshold: string;
  /** Metric value as text, or null when the input is unavailable. */
  readonly value: string | null;
  readonly status: 'PASS' | 'FAIL' | 'UNAVAILABLE';
}

export interface Reason {
  readonly domain: RuleDomain;
  readonly ruleId: string;
  readonly supports: 'BULLISH' | 'BEARISH';
  readonly text: string;
  readonly value: string;
  readonly threshold: string;
}

export interface PlanTarget {
  readonly n: 1 | 2 | 3;
  readonly price: Decimal;
  readonly basis: string;
  /** (target - entry) / (entry - stop), before fees. */
  readonly riskReward: Decimal;
  /** After estimated buy and sell fees/taxes at the planned size; null when the size is 0. */
  readonly netRiskReward: Decimal | null;
  readonly upsidePct: Decimal;
}

export interface TradePlan {
  readonly entryLow: Decimal;
  readonly entryHigh: Decimal;
  readonly entryBasis: string;
  readonly stopLoss: Decimal;
  readonly stopBasis: string;
  readonly targets: readonly PlanTarget[];
  readonly downsidePct: Decimal;
  readonly holdingPeriod: { minTradingDays: number; maxTradingDays: number; label: string };
  readonly quantity: Decimal;
  readonly allocationPct: Decimal;
  readonly sizingBinding: string;
  readonly estimatedBuyCost: Decimal;
  readonly estimatedBuyFees: Decimal;
  /** (entry - stop) x qty + buy fees + sell fees at the stop. */
  readonly maxLoss: Decimal;
}

export interface ConfidenceComponent {
  readonly name: 'DATA_COVERAGE' | 'SIGNAL_AGREEMENT' | 'LIQUIDITY' | 'DATA_QUALITY';
  /** Share of the total (weights sum to 100). */
  readonly weight: number;
  /** 0..100 */
  readonly score: Decimal;
  /** weight x score / 100 */
  readonly contribution: Decimal;
  readonly detail: string;
}
export interface Confidence {
  /** Sum of contributions, 0..100 (after any listed cap). */
  readonly score: Decimal;
  readonly level: 'LOW' | 'MEDIUM' | 'HIGH';
  readonly components: readonly ConfidenceComponent[];
  readonly caps: readonly string[];
}

export interface DataQualityReport {
  readonly sourcesUsed: readonly ResearchDataSource[];
  readonly latestBarSource: ResearchDataSource | null;
  readonly latestBarTs: string | null;
  readonly barsUsed: number;
  readonly ignoredFutureBars: number;
  readonly priceAgeMinutes: Decimal | null;
  readonly freshnessLimitMinutes: number;
  readonly delayMinutes: number | null;
  readonly nonConfirmedBarsInWindow: number;
  readonly fundamentalsSources: readonly ResearchDataSource[];
  readonly missingInputs: readonly string[];
  readonly warnings: readonly string[];
}

export interface RuleScores {
  /** % of available bullish rule weight that passed. */
  readonly bull: Decimal;
  readonly bear: Decimal;
  /** % of total rule weight whose inputs were available. */
  readonly coveragePct: Decimal;
  readonly structuralBearPassed: number;
}

export interface StockEvaluation {
  readonly engineVersion: string;
  readonly symbol: string;
  readonly horizon: Horizon;
  readonly asOf: string;
  readonly status: 'ACTIONABLE' | 'NOT_ACTIONABLE';
  readonly action: RecommendationAction | null;
  readonly headline: string;
  /** Why the evaluation is NOT_ACTIONABLE (empty otherwise). */
  readonly notActionableReasons: readonly string[];
  readonly reasons: readonly Reason[];
  readonly invalidation: readonly string[];
  /** What to watch for (WATCHLIST/HOLD) or caveats. */
  readonly watchFor: readonly string[];
  readonly warnings: readonly string[];
  readonly scores: RuleScores | null;
  readonly rules: readonly RuleOutcome[];
  /** Entry/stop/targets/size: only for STRONG_BUY and BUY, never for NOT_ACTIONABLE. */
  readonly plan: TradePlan | null;
  readonly confidence: Confidence | null;
  readonly valuation: ValuationSummary | null;
  readonly fundamentals: FundamentalsReport | null;
  readonly dataQuality: DataQualityReport;
  readonly disclaimer: string;
}
